    "        line = line.decode('utf-8',errors='replace')\n",
    "        if 'pts_time:' in line:\n",
    "            for part in line.split():\n",
    "                if part.startswith('pts_time:'):\n",
    "                    try: timestamps.append(float(part.split(':')[1]))\n",
    "                    except ValueError: pass\n",
    "                    break\n",
    "    pipe.close()\n",
    "\n",
    "def smooth_1d(arr, k=13):\n",
    "    p = np.pad(arr, k//2, mode='edge')\n",
    "    return np.array([np.median(p[i:i+k]) for i in range(len(arr))])\n",
    "\n",
    "def run_pipeline_on(video_path, yunet_path, output_base='/tmp/task97_batch'):\n",
    "    vinfo = get_video_info(video_path)\n",
    "    native_w, native_h = vinfo['width'], vinfo['height']\n",
    "    duration = vinfo['duration']\n",
    "    det_w = max(64, int(native_w * DET_SCALE))\n",
    "    det_h = max(64, int(native_h * DET_SCALE))\n",
    "    vid_name = os.path.splitext(os.path.basename(video_path))[0][:40]\n",
    "    out_dir = os.path.join(output_base, vid_name)\n",
