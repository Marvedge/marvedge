    "        'verdict': verdict, 'stages': stages,\n",
    "        'sample_crop': vid_tracks[0]['path'] if vid_tracks else None,\n",
    "    }\n",
    "\n",
    "# Auto-discover all videos uploaded to /content\n",
    "VIDEO_EXTS = ('.mp4','.mov','.mkv','.webm','.avi','.m4v')\n",
    "all_videos = sorted([\n",
    "    os.path.join('/content', f) for f in os.listdir('/content')\n",
    "    if f.lower().endswith(VIDEO_EXTS) and os.path.isfile(os.path.join('/content', f))\n",
    "]) if os.path.exists('/content') else []\n",
    "\n",
    "if not all_videos:\n",
    "    print('No videos found in /content!')\n",
